'use strict';
// PRD v7 T-94 (R-08, S-23) — the 72-run schedule.
//
// Eight briefs, three arms, three matched repetitions. The v6 edition compared two arms
// and could alternate; three arms need a Latin square, because "balanced" has to mean
// more than "not always the same one first". Two properties are asserted by the suite:
//
//   * each brief starts with each of the three arms exactly once across its three
//     repetitions, so no brief is systematically warmed up for one arm;
//   * the total count of first positions is equal per arm (24 first positions, 8 each),
//     so no arm is systematically advantaged across the study.
//
// Rotating the arm order by (brief index + repetition) gives both at once. There is no
// randomness here on purpose: a schedule that cannot be regenerated byte for byte from
// the brief list cannot be checked by a reader, and Date/Math.random would also break
// the workflow resume contract the rest of this tooling relies on.
const effort = require('./effort.cjs');
const briefs = require('./briefs.cjs');

const ARMS = effort.ARMS;           // ['plain', 'pincer', 'strict']
const REPETITIONS = 3;
const MAX_REPETITION = 9;           // reruns of invalidated cells take numbers above the schedule

// The arm order for one cell of the square.
const armOrder = (briefIndex, repetition) =>
  ARMS.map((_, k) => ARMS[(briefIndex + repetition + k) % ARMS.length]);

// schedule(ids) → [{ order, brief, repetition, arm, run }] in execution order.
function schedule(ids = briefs.briefIds()) {
  const runs = [];
  let order = 0;
  for (let repetition = 1; repetition <= REPETITIONS; repetition++) {
    ids.forEach((brief, index) => {
      for (const arm of armOrder(index, repetition)) {
        runs.push({ order: ++order, brief, repetition, arm, run: effort.runId(brief, repetition, arm) });
      }
    });
  }
  return runs;
}

// The three arms of one brief-repetition. They must receive identical task intent, base
// repository, model, tool versions and caps; only the workspace preparation differs.
const cell = (runs, brief, repetition) => runs.filter(r => r.brief === brief && r.repetition === repetition);
// The first arm of each cell, which is what "balanced order" is a claim about.
const firstArms = runs => {
  const seen = new Set();
  return runs.filter(r => {
    const key = `${r.brief}/${r.repetition}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
};

// What a reader needs to see that the schedule is balanced, without re-deriving it.
function balance(runs) {
  const firsts = firstArms(runs);
  const perArm = Object.fromEntries(ARMS.map(a => [a, firsts.filter(r => r.arm === a).length]));
  const perBrief = {};
  for (const r of firsts) (perBrief[r.brief] ||= []).push(r.arm);
  return {
    cells: firsts.length,
    first_positions: perArm,
    // True when every brief opened with every arm exactly once.
    every_brief_starts_with_every_arm: Object.values(perBrief).every(list => new Set(list).size === ARMS.length && list.length === ARMS.length),
    equal_first_positions: new Set(Object.values(perArm)).size === 1,
  };
}

module.exports = { ARMS, REPETITIONS, MAX_REPETITION, armOrder, schedule, cell, firstArms, balance };
