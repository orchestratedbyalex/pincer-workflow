'use strict';
// PINCER blueprint — the generator (docs/engine.md, "Generate"). From the library
// and harness.json it writes, for every stage that is on, the project copy of the
// stage folder, a thin command and, per platform, the Codex skill and the Copilot
// prompt derived from the project copy; for every agent in an active roster, its
// copy. Baselines live in .pincer.json when the installer wrote one. A target
// whose hash matches neither its baseline nor the fresh content was edited by
// hand: it is kept and the fresh content lands beside it as <file>.new.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const util = require('./util.cjs');
const harness = require('./harness.cjs');

const LIBRARY = '.claude/pincer/library';
const MANIFEST = '.pincer.json';
const PLATFORMS = ['claude', 'codex', 'copilot'];
const COPILOT_INPUT = '${input:request:Task brief or arguments (optional)}';
const KEEP_DIRS = new Set(['.claude', '.agents', '.github']);

const sha = (data) => crypto.createHash('sha256').update(data).digest('hex');
const isObject = (value) => value !== null && typeof value === 'object' && !Array.isArray(value);
const isDir = (p) => { try { return fs.statSync(p).isDirectory(); } catch { return false; } };
const hashOf = (abs) => (fs.existsSync(abs) ? sha(fs.readFileSync(abs)) : null);
const MARKER = '<!-- Generated by scripts/pincer/cli.cjs generate from ';
const generatedComment = (source) => `${MARKER}${source} — edit the project copy, not this file -->`;
// Derived files (command, Codex skill, Copilot prompt) carry the marker; one that
// still does is the generator's to overwrite or remove, whatever its baseline.
const DERIVED_PATH = /^(\.claude\/commands\/pincer-[a-z-]+\.md|\.agents\/skills\/pincer-[a-z-]+\/SKILL\.md|\.github\/prompts\/pincer-[a-z-]+\.prompt\.md)$/;
const carriesMarker = (abs) => { try { return fs.readFileSync(abs, 'utf8').includes(MARKER); } catch { return false; } };

// The project's library when it has one, else the kit's own copy next to this file.
function libraryDir(root, override) {
  if (override) return path.resolve(root, override);
  const own = path.join(root, LIBRARY);
  return fs.existsSync(own) ? own : path.resolve(__dirname, '..', '..', LIBRARY);
}

// The platforms the installer recorded; all three when there is no usable manifest.
function manifestPlatforms(root) {
  const manifest = util.readJson(path.join(root, MANIFEST));
  const list = manifest && Array.isArray(manifest.platforms) ? manifest.platforms : null;
  return list && list.length && list.every((p) => PLATFORMS.includes(p)) ? [...new Set(list)] : [...PLATFORMS];
}

// Every file under dir as sorted posix paths relative to it.
function listFiles(dir, rel = '') {
  const abs = path.join(dir, rel);
  if (!isDir(abs)) return [];
  const out = [];
  const entries = fs.readdirSync(abs, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1));
  for (const entry of entries) {
    if (entry.name === '.DS_Store') continue;
    const child = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...listFiles(dir, child));
    else if (entry.isFile()) out.push(child);
  }
  return out;
}

// key: value lines between the first two --- lines; quotes around a value are dropped.
function splitFrontmatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text);
  if (!match) return { fields: {}, body: text };
  const fields = {};
  for (const line of match[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let value = kv[2].trim();
    const q = value[0];
    if (value.length >= 2 && (q === '"' || q === "'") && value.endsWith(q)) value = value.slice(1, -1);
    fields[kv[1]] = value;
  }
  return { fields, body: text.slice(match[0].length) };
}
const quoted = (value) => JSON.stringify(String(value));
const bodyText = (body) => { const text = body.replace(/^\n+/, ''); return text.endsWith('\n') ? text : `${text}\n`; };
const describe = (stage, fields) => fields.description || `PINCER ${stage} stage`;
const skillDir = (stage) => `.claude/skills/pincer-${stage}`;
const skillFile = (stage) => `${skillDir(stage)}/SKILL.md`;
const agentPath = (name) => `.claude/agents/${name}.md`;

// /pincer-x becomes $pincer-x where it is a command mention: at a line start or
// after a character that cannot be part of a path, so scripts/pincer-status.sh stays.
const codexMentions = (text) => text.replace(/(^|[^A-Za-z0-9_./])\/pincer-([a-z][a-z-]*)/gm, (_, before, name) => `${before}$pincer-${name}`);

function renderCommand(stage, fields) {
  const hint = fields['argument-hint'] ? `argument-hint: ${quoted(fields['argument-hint'])}\n` : '';
  return `---\ndescription: ${quoted(describe(stage, fields))}\n${hint}---\n${generatedComment(skillFile(stage))}\n\nRead ${skillFile(stage)} and follow it. Arguments: $ARGUMENTS\n`;
}
function renderCodex(stage, fields, body) {
  const optional = !fields['argument-hint'] || /optional/i.test(fields['argument-hint']);
  const sentence = optional
    ? `the text that follows the \`$pincer-${stage}\` mention, if any (when omitted, use the skill's documented default)`
    : `the text that follows the \`$pincer-${stage}\` mention in the user's message (ask only if the required input is missing)`;
  const text = codexMentions(body.split('$ARGUMENTS').join(sentence));
  return `---\nname: pincer-${stage}\ndescription: ${quoted(describe(stage, fields))}\n---\n${generatedComment(skillFile(stage))}\n\n${bodyText(text)}`;
}
function renderCopilot(stage, fields, body) {
  const text = body.split('$ARGUMENTS').join(COPILOT_INPUT);
  return `---\nmode: agent\ndescription: ${quoted(describe(stage, fields))}\n---\n${generatedComment(skillFile(stage))}\n\n${bodyText(text)}`;
}
// The files derived from a stage's SKILL.md text, keyed by path (every platform).
function derived(stage, skillText) {
  const { fields, body } = splitFrontmatter(skillText);
  return {
    [`.claude/commands/pincer-${stage}.md`]: renderCommand(stage, fields),
    [`.agents/skills/pincer-${stage}/SKILL.md`]: renderCodex(stage, fields, body),
    [`.github/prompts/pincer-${stage}.prompt.md`]: renderCopilot(stage, fields, body),
  };
}
function derivedPaths(stage, platforms) {
  const out = [`.claude/commands/pincer-${stage}.md`];
  if (platforms.includes('codex')) out.push(`.agents/skills/pincer-${stage}/SKILL.md`);
  if (platforms.includes('copilot')) out.push(`.github/prompts/pincer-${stage}.prompt.md`);
  return out;
}
// A path belongs to the platforms asked about; others are left alone.
const inScope = (rel, platforms) => (rel.startsWith('.agents/') ? platforms.includes('codex') : rel.startsWith('.github/') ? platforms.includes('copilot') : true);

// The agents named by the rosters of the stages that are on.
function activeAgents(h) {
  const names = new Set();
  for (const stage of harness.ROSTER_STAGES) if (harness.stageOn(h, stage)) for (const name of (h.roster && h.roster[stage]) || []) names.add(name);
  return [...names].sort();
}

// Every path the generator owns for this agreement and these platforms. With a
// library the project copies list the whole stage folder, else SKILL.md alone.
function generatedPaths(doc, platforms = PLATFORMS, { library } = {}) {
  const h = harness.normalize(doc);
  const out = [];
  for (const stage of harness.STAGES) {
    if (!harness.stageOn(h, stage)) continue;
    const files = library ? listFiles(path.join(library, 'stages', stage)) : [];
    for (const file of files.length ? files : ['SKILL.md']) out.push(`${skillDir(stage)}/${file}`);
    out.push(...derivedPaths(stage, platforms));
  }
  for (const name of activeAgents(h)) out.push(agentPath(name));
  return out;
}

// Remove empty directories upward, never the platform roots or the project root.
function pruneEmpty(root, dir) {
  for (;;) {
    const rel = path.relative(root, dir);
    if (!rel || rel.startsWith('..') || KEEP_DIRS.has(rel)) return;
    try { if (fs.readdirSync(dir).length) return; fs.rmdirSync(dir); } catch { return; }
    dir = path.dirname(dir);
  }
}

function generate(root, { harness: doc, platforms = manifestPlatforms(root), library, overwrite = false } = {}) {
  if (!isObject(doc)) throw new TypeError('generate needs a harness');
  const h = harness.normalize(doc);
  const lib = libraryDir(root, library);
  const manifestFile = path.join(root, MANIFEST);
  const manifest = util.readJson(manifestFile);
  const baseline = manifest && isObject(manifest.generated) ? manifest.generated : {};
  const next = {};
  const report = { written: [], skipped: [], conflicted: [], removed: [], missing: [] };
  const expected = new Set();

  // Put fresh content at rel unless the file there was edited by hand; returns the
  // content now on disk, which the derived files follow.
  const place = (rel, fresh) => {
    expected.add(rel);
    const abs = path.join(root, rel);
    const buf = Buffer.isBuffer(fresh) ? fresh : Buffer.from(fresh, 'utf8');
    const freshHash = sha(buf);
    const current = hashOf(abs);
    const ours = overwrite || current === freshHash || current === baseline[rel] || (DERIVED_PATH.test(rel) && carriesMarker(abs));
    if (current !== null && !ours) {
      const sidecar = `${abs}.new`;
      if (hashOf(sidecar) !== freshHash) util.atomicWrite(sidecar, buf);
      report.conflicted.push(rel);
      if (baseline[rel]) next[rel] = baseline[rel];
      return fs.readFileSync(abs);
    }
    if (current === freshHash) report.skipped.push(rel);
    else { util.atomicWrite(abs, buf); report.written.push(rel); }
    next[rel] = freshHash;
    return buf;
  };

  for (const stage of harness.STAGES) {
    if (!harness.stageOn(h, stage)) continue;
    const src = path.join(lib, 'stages', stage);
    if (!fs.existsSync(path.join(src, 'SKILL.md'))) { report.missing.push(stage); continue; }
    let skillText = '';
    for (const file of listFiles(src)) {
      const placed = place(`${skillDir(stage)}/${file}`, fs.readFileSync(path.join(src, file)));
      if (file === 'SKILL.md') skillText = placed.toString('utf8');
    }
    const outputs = derived(stage, skillText);
    for (const rel of derivedPaths(stage, platforms)) place(rel, outputs[rel]);
  }
  const agents = activeAgents(h);
  for (const name of agents) {
    const src = path.join(lib, 'agents', `${name}.md`);
    if (!fs.existsSync(src)) { report.missing.push(`agents/${name}`); continue; }
    place(agentPath(name), fs.readFileSync(src));
  }

  // Removals: what an earlier run recorded, or what an off stage or a dropped agent
  // would own, when it is not expected now and still reads as generated: equal to
  // its baseline or to the library's copy, or a derived file carrying the marker.
  const pristine = {};
  const candidates = new Set();
  for (const rel of Object.keys(baseline)) { if (inScope(rel, platforms)) candidates.add(rel); else next[rel] = baseline[rel]; }
  for (const stage of harness.STAGES) {
    if (harness.stageOn(h, stage)) continue;
    const src = path.join(lib, 'stages', stage);
    for (const file of listFiles(src)) pristine[`${skillDir(stage)}/${file}`] = sha(fs.readFileSync(path.join(src, file)));
    for (const file of listFiles(path.join(root, skillDir(stage)))) if (!file.endsWith('.new')) candidates.add(`${skillDir(stage)}/${file}`);
    for (const rel of derivedPaths(stage, platforms)) candidates.add(rel);
  }
  for (const name of harness.AGENT_NAMES) {
    if (agents.includes(name)) continue;
    const src = path.join(lib, 'agents', `${name}.md`);
    if (fs.existsSync(src)) pristine[agentPath(name)] = sha(fs.readFileSync(src));
    candidates.add(agentPath(name));
  }
  for (const rel of [...candidates].sort()) {
    if (expected.has(rel)) continue;
    const abs = path.join(root, rel);
    const current = hashOf(abs);
    if (current === null) continue;
    if (overwrite || current === baseline[rel] || current === pristine[rel] || (DERIVED_PATH.test(rel) && carriesMarker(abs))) {
      fs.unlinkSync(abs);
      report.removed.push(rel);
      pruneEmpty(root, path.dirname(abs));
    } else {
      report.conflicted.push(rel);
      if (baseline[rel]) next[rel] = baseline[rel];
    }
  }

  if (isObject(manifest)) {
    manifest.generated = Object.fromEntries(Object.keys(next).sort().map((rel) => [rel, next[rel]]));
    util.atomicWrite(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`);
  }
  return report;
}

module.exports = { LIBRARY, MANIFEST, PLATFORMS, generate, generatedPaths, manifestPlatforms, libraryDir, splitFrontmatter, codexMentions, activeAgents };
