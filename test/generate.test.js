// The generator: project copies of the stage skills, thin commands, Codex skills,
// Copilot prompts and agent copies from a library, with baselines in .pincer.json
// and .new sidecars for edited copies. Uses a tiny fixture library, not the real one.
// Run with: node test/generate.test.js
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { repo, tempDir, run, write, read, createHarness } from './helpers.js';

const require = createRequire(import.meta.url);
const gen = require(path.join(repo, 'template/scripts/pincer/generate.cjs'));
const harness = require(path.join(repo, 'template/scripts/pincer/harness.cjs'));
const cliFile = path.join(repo, 'template/scripts/pincer/cli.cjs');
const syncScript = path.join(repo, 'template/scripts/sync-prompts.sh');
const both = (r) => `${r.stdout}${r.stderr}`;
const exists = (dir, rel) => fs.existsSync(path.join(dir, rel));
const sha = (text) => crypto.createHash('sha256').update(text).digest('hex');
const GENERATED = /^<!-- Generated by scripts\/pincer\/cli\.cjs generate from (\S+) — edit the project copy, not this file -->$/m;

const PLAN_SKILL = `---
name: pincer-plan
description: "Brief to a written spec"
argument-hint: "<brief>"
---
# Plan

Run /pincer-status first, then \`/pincer-narrow\` when the spec is approved.
Keep scripts/pincer-status.sh and .claude/skills/pincer-plan/prompts/ask.md as written.
Arguments: $ARGUMENTS
Quoted arguments: \`$ARGUMENTS\`
`;
const STATUS_SKILL = `---
name: pincer-status
description: Where the work stands and the next command
argument-hint: "[--json] (optional)"
---
# Status

/pincer-status prints the report. Arguments: $ARGUMENTS
`;
const EXPLORER = `---
name: codebase-explorer
description: Maps the code a change touches
---
Read before you write.
`;
function fixtureLibrary(dir, lib = 'lib') {
  write(dir, `${lib}/stages/plan/SKILL.md`, PLAN_SKILL);
  write(dir, `${lib}/stages/plan/prompts/ask.md`, 'Ask the person for the brief.\n');
  write(dir, `${lib}/stages/status/SKILL.md`, STATUS_SKILL);
  write(dir, `${lib}/agents/codebase-explorer.md`, EXPLORER);
  return lib;
}
const OFF = { narrow: { on: false }, code: { on: false }, evaluate: { on: false }, release: { on: false } };
const planOn = () => harness.normalize({ schema: 1, project: { name: 'example', kind: 'greenfield' }, people: [{ name: 'Alex', accepts: true }], stages: { plan: { on: true }, ...OFF }, roster: { plan: ['codebase-explorer'] } });
const ALL = ['claude', 'codex', 'copilot'];
const PLAN_PATHS = ['.claude/skills/pincer-plan/SKILL.md', '.claude/skills/pincer-plan/prompts/ask.md', '.claude/commands/pincer-plan.md', '.agents/skills/pincer-plan/SKILL.md', '.github/prompts/pincer-plan.prompt.md'];
const STATUS_PATHS = ['.claude/skills/pincer-status/SKILL.md', '.claude/commands/pincer-status.md', '.agents/skills/pincer-status/SKILL.md', '.github/prompts/pincer-status.prompt.md'];
const AGENT_PATH = '.claude/agents/codebase-explorer.md';
const CODEX_AGENT_PATH = '.codex/agents/codebase-explorer.toml';

assert.equal(gen.LIBRARY, '.claude/pincer/library');

// generatedPaths: the fixed paths per on stage and active agent, per platform
let paths = gen.generatedPaths(planOn(), ALL);
for (const p of [...PLAN_PATHS.filter((p) => !p.includes('prompts/')), ...STATUS_PATHS, AGENT_PATH, '.claude/skills/pincer-blueprint/SKILL.md']) assert.ok(paths.includes(p), p);
assert.ok(!paths.some((p) => p.includes('pincer-narrow')), paths.join('\n'));
paths = gen.generatedPaths(planOn(), ['claude']);
assert.ok(!paths.some((p) => p.startsWith('.agents/') || p.startsWith('.github/')), paths.join('\n'));

// First run: every file for plan, status and the agent; blueprint is reported missing from the fixture
let dir = tempDir();
let lib = fixtureLibrary(dir);
let report = gen.generate(dir, { harness: planOn(), platforms: ALL, library: lib });
assert.deepEqual(report.written.sort(), [...PLAN_PATHS, ...STATUS_PATHS, AGENT_PATH, CODEX_AGENT_PATH].sort());
assert.deepEqual(report.skipped, []);
assert.deepEqual(report.conflicted, []);
assert.deepEqual(report.removed, []);
assert.deepEqual(report.missing, ['blueprint']);
for (const p of [...PLAN_PATHS, ...STATUS_PATHS, AGENT_PATH, CODEX_AGENT_PATH]) assert.ok(exists(dir, p), p);
assert.ok(!exists(dir, '.pincer.json'), 'no manifest is created');
// the project copy and the agent copy are byte copies of the library, no comment
assert.equal(read(dir, '.claude/skills/pincer-plan/SKILL.md'), PLAN_SKILL);
assert.equal(read(dir, '.claude/skills/pincer-plan/prompts/ask.md'), 'Ask the person for the brief.\n');
assert.equal(read(dir, AGENT_PATH), EXPLORER);
// the thin command: description and argument-hint copied, one body line
let command = read(dir, '.claude/commands/pincer-plan.md');
assert.ok(command.startsWith('---\ndescription: "Brief to a written spec"\nargument-hint: "<brief>"\n---\n'), command);
assert.match(command, GENERATED);
assert.equal(GENERATED.exec(command)[1], '.claude/skills/pincer-plan/SKILL.md');
assert.ok(command.trimEnd().endsWith('Read .claude/skills/pincer-plan/SKILL.md and follow it. Arguments: $ARGUMENTS'), command);
assert.ok(!read(dir, '.claude/commands/pincer-status.md').includes('argument-hint: "<brief>"'));
assert.match(read(dir, '.claude/commands/pincer-status.md'), /^argument-hint: "\[--json\] \(optional\)"$/m);
// Codex: $pincer- mentions, paths intact, the argument sentence, the comment on the first body line
let codex = read(dir, '.agents/skills/pincer-plan/SKILL.md');
assert.ok(codex.startsWith('---\nname: pincer-plan\ndescription: "Brief to a written spec"\n---\n<!-- Generated by'), codex);
assert.equal(GENERATED.exec(codex)[1], '.claude/skills/pincer-plan/SKILL.md');
assert.ok(codex.includes('Run $pincer-status first, then `$pincer-narrow` when'), codex);
assert.ok(!/(^|[^A-Za-z0-9_./])\/pincer-/m.test(codex), 'no command mention left as /pincer-:\n' + codex);
assert.ok(codex.includes('scripts/pincer-status.sh and .claude/skills/pincer-plan/prompts/ask.md'), codex);
assert.ok(!codex.includes('$ARGUMENTS'), codex);
assert.ok(codex.includes('Arguments: the text that follows the `$pincer-plan` mention in the user\'s message (ask only if the required input is missing)'), codex);
assert.ok(codex.includes('Quoted arguments: the text that follows the `$pincer-plan` mention'), codex);
assert.ok(!codex.includes('`the text that follows'), 'argument expansion must not nest code spans');
const codexStatus = read(dir, '.agents/skills/pincer-status/SKILL.md');
assert.ok(codexStatus.includes('the text that follows the `$pincer-status` mention, if any'), codexStatus);
assert.ok(codexStatus.includes('\n$pincer-status prints the report.'), codexStatus);
// Copilot: mode agent, the input variable, the comment
let copilot = read(dir, '.github/prompts/pincer-plan.prompt.md');
assert.ok(copilot.startsWith('---\nmode: agent\ndescription: "Brief to a written spec"\n---\n<!-- Generated by'), copilot);
assert.ok(copilot.includes('Arguments: ${input:request:Task brief or arguments (optional)}'), copilot);
assert.ok(copilot.includes('Run /pincer-status first'), copilot);
assert.ok(!copilot.includes('$ARGUMENTS'));

// Second run: nothing changes, everything skipped, files byte-identical
const snapshot = Object.fromEntries([...PLAN_PATHS, ...STATUS_PATHS, AGENT_PATH, CODEX_AGENT_PATH].map((p) => [p, read(dir, p)]));
report = gen.generate(dir, { harness: planOn(), platforms: ALL, library: lib });
assert.deepEqual(report.written, []);
assert.deepEqual(report.skipped.sort(), [...PLAN_PATHS, ...STATUS_PATHS, AGENT_PATH, CODEX_AGENT_PATH].sort());
assert.deepEqual(report.conflicted, []);
for (const [p, text] of Object.entries(snapshot)) assert.equal(read(dir, p), text, p);

// An edited project copy stays, gets a .new sidecar, and the Codex and Copilot files follow the edit
const edited = PLAN_SKILL.replace('# Plan', '# Plan (ours)\n\nOur extra step.');
write(dir, '.claude/skills/pincer-plan/SKILL.md', edited);
report = gen.generate(dir, { harness: planOn(), platforms: ALL, library: lib });
assert.equal(read(dir, '.claude/skills/pincer-plan/SKILL.md'), edited);
assert.equal(read(dir, '.claude/skills/pincer-plan/SKILL.md.new'), PLAN_SKILL);
assert.deepEqual(report.conflicted, ['.claude/skills/pincer-plan/SKILL.md']);
assert.ok(report.written.includes('.agents/skills/pincer-plan/SKILL.md'), report.written.join('\n'));
assert.ok(read(dir, '.agents/skills/pincer-plan/SKILL.md').includes('Our extra step.'));
assert.ok(read(dir, '.github/prompts/pincer-plan.prompt.md').includes('Our extra step.'));
// again: still conflicted, sidecar unchanged, nothing else written
report = gen.generate(dir, { harness: planOn(), platforms: ALL, library: lib });
assert.deepEqual(report.conflicted, ['.claude/skills/pincer-plan/SKILL.md']);
assert.deepEqual(report.written, []);
assert.equal(read(dir, '.claude/skills/pincer-plan/SKILL.md.new'), PLAN_SKILL);
// --overwrite puts the library copy back
report = gen.generate(dir, { harness: planOn(), platforms: ALL, library: lib, overwrite: true });
assert.equal(read(dir, '.claude/skills/pincer-plan/SKILL.md'), PLAN_SKILL);
assert.deepEqual(report.conflicted, []);
assert.ok(report.written.includes('.claude/skills/pincer-plan/SKILL.md'));

// Plan switched off: unedited generated files go, an edited project copy stays and is reported
write(dir, '.claude/skills/pincer-plan/SKILL.md', edited);
gen.generate(dir, { harness: planOn(), platforms: ALL, library: lib });
const planOff = harness.normalize({ ...planOn(), stages: { plan: { on: false, reason: 'tickets are the spec' }, ...OFF } });
report = gen.generate(dir, { harness: planOff, platforms: ALL, library: lib });
for (const p of ['.claude/commands/pincer-plan.md', '.agents/skills/pincer-plan/SKILL.md', '.github/prompts/pincer-plan.prompt.md', '.claude/skills/pincer-plan/prompts/ask.md', AGENT_PATH, CODEX_AGENT_PATH]) {
  assert.ok(!exists(dir, p), `${p} should be removed`);
  assert.ok(report.removed.includes(p), p);
}
assert.ok(!exists(dir, '.agents/skills/pincer-plan'), 'empty Codex skill dir pruned');
assert.equal(read(dir, '.claude/skills/pincer-plan/SKILL.md'), edited);
assert.deepEqual(report.retained, ['.claude/skills/pincer-plan/SKILL.md'], 'a removal conflict is retained, not a sidecar conflict');
assert.deepEqual(report.conflicted, []);
for (const p of STATUS_PATHS) assert.ok(exists(dir, p), p);
// back on: the edited copy is still honoured, the derived files come back from it
report = gen.generate(dir, { harness: planOn(), platforms: ALL, library: lib });
assert.ok(read(dir, '.agents/skills/pincer-plan/SKILL.md').includes('Our extra step.'));
assert.ok(exists(dir, AGENT_PATH));

// Baselines in .pincer.json: recorded when the manifest exists, other keys kept, edits detected by hash
dir = tempDir();
lib = fixtureLibrary(dir);
write(dir, '.pincer.json', JSON.stringify({ schema: 3, version: '1.0.0', platforms: ['claude', 'codex'], files: { 'AGENTS.md': 'abc' }, generated: {} }, null, 2) + '\n');
report = gen.generate(dir, { harness: planOn(), library: lib });
assert.ok(!report.written.some((p) => p.startsWith('.github/')), 'platforms come from the manifest');
assert.ok(report.written.includes('.agents/skills/pincer-plan/SKILL.md'));
let manifest = JSON.parse(read(dir, '.pincer.json'));
assert.equal(manifest.schema, 3);
assert.deepEqual(manifest.files, { 'AGENTS.md': 'abc' });
assert.deepEqual(manifest.platforms, ['claude', 'codex']);
assert.equal(manifest.generated['.claude/skills/pincer-plan/SKILL.md'], sha(PLAN_SKILL));
assert.equal(manifest.generated['.claude/agents/codebase-explorer.md'], sha(EXPLORER));
assert.deepEqual(Object.keys(manifest.generated).sort(), report.written.slice().sort());
// the library changes while the copy is untouched: overwritten, baseline moves
write(dir, `${lib}/stages/plan/SKILL.md`, PLAN_SKILL.replace('Keep scripts', 'Always keep scripts'));
report = gen.generate(dir, { harness: planOn(), library: lib });
assert.ok(report.written.includes('.claude/skills/pincer-plan/SKILL.md'));
assert.ok(read(dir, '.claude/skills/pincer-plan/SKILL.md').includes('Always keep scripts'));
assert.ok(!exists(dir, '.claude/skills/pincer-plan/SKILL.md.new'));
manifest = JSON.parse(read(dir, '.pincer.json'));
assert.equal(manifest.generated['.claude/skills/pincer-plan/SKILL.md'], sha(read(dir, '.claude/skills/pincer-plan/SKILL.md')));
// the copy is edited AND the library changes: the edit stays, the sidecar has the new library text
write(dir, '.claude/skills/pincer-plan/SKILL.md', edited);
write(dir, `${lib}/stages/plan/SKILL.md`, PLAN_SKILL.replace('Keep scripts', 'Never drop scripts'));
report = gen.generate(dir, { harness: planOn(), library: lib });
assert.deepEqual(report.conflicted, ['.claude/skills/pincer-plan/SKILL.md']);
assert.equal(read(dir, '.claude/skills/pincer-plan/SKILL.md'), edited);
assert.ok(read(dir, '.claude/skills/pincer-plan/SKILL.md.new').includes('Never drop scripts'));
manifest = JSON.parse(read(dir, '.pincer.json'));
assert.equal(manifest.generated['.claude/skills/pincer-plan/SKILL.md'], sha(PLAN_SKILL.replace('Keep scripts', 'Always keep scripts')), 'baseline kept at the last generated content');
// the developer adopts the sidecar: the copy equals the fresh content, so it is current again
fs.renameSync(path.join(dir, '.claude/skills/pincer-plan/SKILL.md.new'), path.join(dir, '.claude/skills/pincer-plan/SKILL.md'));
report = gen.generate(dir, { harness: planOn(), library: lib });
assert.deepEqual(report.conflicted, []);
assert.ok(report.skipped.includes('.claude/skills/pincer-plan/SKILL.md'));
// off with a baseline: removed files leave the baseline, the edited one stays in it
write(dir, '.agents/skills/pincer-plan/SKILL.md', 'hand-edited codex copy\n');
report = gen.generate(dir, { harness: planOff, library: lib });
assert.ok(report.removed.includes('.claude/commands/pincer-plan.md'));
assert.deepEqual(report.retained, ['.agents/skills/pincer-plan/SKILL.md']);
assert.deepEqual(report.conflicted, []);
assert.equal(read(dir, '.agents/skills/pincer-plan/SKILL.md'), 'hand-edited codex copy\n');
manifest = JSON.parse(read(dir, '.pincer.json'));
assert.equal(manifest.generated['.claude/commands/pincer-plan.md'], undefined);
assert.ok(manifest.generated['.agents/skills/pincer-plan/SKILL.md']);
assert.ok(manifest.generated['.claude/skills/pincer-status/SKILL.md']);

// A derived file edited by hand keeps the generated comment but differs from its baseline: kept, with a sidecar (review I3)
dir = tempDir();
lib = fixtureLibrary(dir);
write(dir, '.pincer.json', JSON.stringify({ schema: 3, version: '1.0.0', platforms: ALL, files: {}, generated: {} }));
gen.generate(dir, { harness: planOn(), library: lib });
const codexCopy = read(dir, '.agents/skills/pincer-plan/SKILL.md');
assert.ok(codexCopy.includes('<!-- Generated by'), 'the derived file carries the marker');
write(dir, '.agents/skills/pincer-plan/SKILL.md', codexCopy + '\nCODEX USER EDIT\n');
report = gen.generate(dir, { harness: planOn(), library: lib });
assert.ok(read(dir, '.agents/skills/pincer-plan/SKILL.md').includes('CODEX USER EDIT'), 'the hand edit survives');
assert.equal(read(dir, '.agents/skills/pincer-plan/SKILL.md.new'), codexCopy);
assert.deepEqual(report.conflicted, ['.agents/skills/pincer-plan/SKILL.md']);
// without a baseline the marker still decides: a stale derived copy is refreshed
fs.unlinkSync(path.join(dir, '.pincer.json'));
fs.unlinkSync(path.join(dir, '.agents/skills/pincer-plan/SKILL.md.new'));
report = gen.generate(dir, { harness: planOn(), library: lib });
assert.ok(report.written.includes('.agents/skills/pincer-plan/SKILL.md'));
assert.ok(!read(dir, '.agents/skills/pincer-plan/SKILL.md').includes('CODEX USER EDIT'));

// A baseline key that points outside the root is never a removal candidate (review C1)
dir = tempDir();
lib = fixtureLibrary(dir);
