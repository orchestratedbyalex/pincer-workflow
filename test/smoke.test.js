// A fresh install: init writes the kit for the chosen platforms, the engine runs
// in it before any agreement exists, doctor is clean and points at the blueprint.
// Run with: node test/smoke.test.js
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { repo, tempDir, run, write, read } from './helpers.js';
import { PLATFORM_ROOTS, EXECUTABLES, MANIFEST_SCHEMA, GITIGNORE_LINES } from '../bin/pincer.js';

const bin = path.join(repo, 'bin/pincer.js');
const pincer = (dir, ...args) => run(dir, process.execPath, [bin, ...args]);
const both = (r) => `${r.stdout}${r.stderr}`;
const exists = (dir, rel) => fs.existsSync(path.join(dir, rel));

const dir = tempDir();
let r = pincer(dir, 'init', '--platform', 'all');
assert.equal(r.status, 0, both(r));
for (const needle of ['/pincer-blueprint', '$pincer-blueprint', 'scripts/pincer-status.sh', 'chat.promptFiles']) assert.ok(r.stdout.includes(needle), `init next steps name ${needle}:\n${r.stdout}`);
assert.ok(!r.stdout.includes('pincer-plan'), 'the next step is the blueprint, not plan');

// the manifest: schema 3, the platforms, every file it lists exists, baselines for the generator start empty
const manifest = JSON.parse(read(dir, '.pincer.json'));
assert.equal(manifest.schema, MANIFEST_SCHEMA);
assert.deepEqual(manifest.platforms, ['claude', 'codex', 'copilot']);
assert.deepEqual(manifest.generated, {});
const roots = [...PLATFORM_ROOTS.common, ...PLATFORM_ROOTS.claude, ...PLATFORM_ROOTS.codex, ...PLATFORM_ROOTS.copilot];
for (const root of roots) assert.ok(exists(dir, root), `installed: ${root}`);
for (const rel of Object.keys(manifest.files)) {
  assert.ok(exists(dir, rel), rel);
  assert.ok(!/pincer-runtime|\.prd|\.claude\/references|runtime-contracts|dry-run/.test(rel), `retired path shipped: ${rel}`);
}
for (const rel of EXECUTABLES) assert.ok(fs.statSync(path.join(dir, rel)).mode & 0o100, `${rel} executable`);
const gitignore = read(dir, '.gitignore').split('\n').map((l) => l.trim());
for (const line of GITIGNORE_LINES) assert.ok(gitignore.includes(line), `.gitignore: ${line}`);
assert.ok(!gitignore.some((l) => l.includes('.pincer')), 'no runtime ignore line');

// the engine runs in the fresh install, before any agreement
r = run(dir, 'bash', ['scripts/pincer-status.sh']);
assert.equal(r.status, 0, both(r));
assert.match(r.stdout, /no agreement yet/);
assert.match(r.stdout, /Next: \/pincer-blueprint/);
assert.equal(run(dir, 'bash', ['scripts/pincer-status.sh', '--stage', 'code']).status, 3);
assert.equal(run(dir, 'bash', ['scripts/pincer-status.sh', '--stage', 'blueprint']).status, 0);
assert.equal(run(dir, 'bash', ['scripts/pincer-ticket.sh', 'start', 'T-01']).status, 3);
r = run(dir, process.execPath, ['scripts/pincer-blueprint.cjs', 'recon', '--json']);
assert.equal(r.status, 0, both(r));
assert.equal(JSON.parse(r.stdout).kind, 'greenfield');
// the shipped copies of the always-on stages are in place
assert.ok(read(dir, '.claude/commands/pincer-blueprint.md').includes('Read .claude/skills/pincer-blueprint/SKILL.md and follow it'));
assert.ok(read(dir, '.agents/skills/pincer-status/SKILL.md').includes('$pincer-blueprint'));
assert.match(read(dir, '.github/prompts/pincer-blueprint.prompt.md'), /^mode: agent$/m);
assert.ok(exists(dir, '.claude/pincer/library/stages/release/SKILL.md'), 'the whole library ships');
assert.ok(!exists(dir, '.claude/skills/pincer-plan'), 'optional stages are generated by the blueprint, not shipped');

// doctor: clean, with the harness note; then ok with a valid agreement; FAIL with a broken one
r = pincer(dir, 'doctor');
assert.equal(r.status, 0, both(r));
assert.match(r.stdout, /note\s+no harness\.json yet — run \/pincer-blueprint/);
assert.ok(!/pincer-runtime|migrat|\.prd/i.test(r.stdout), r.stdout);
write(dir, 'harness.json', JSON.stringify({ schema: 1, project: { name: 'x', kind: 'greenfield' }, people: [{ name: 'Alex', accepts: true }] }));
r = pincer(dir, 'doctor');
assert.equal(r.status, 0, both(r));
assert.match(r.stdout, /ok\s+harness\.json valid/);
write(dir, 'harness.json', '{"schema": 2}');
r = pincer(dir, 'doctor');
assert.equal(r.status, 1, both(r));
assert.match(r.stdout, /FAIL\s+harness\.json: schema must be 1/);
write(dir, 'harness.json', '{');
r = pincer(dir, 'doctor');
assert.equal(r.status, 1, both(r));
assert.match(r.stdout, /FAIL\s+harness\.json: invalid JSON/);

// init twice is refused
r = pincer(dir, 'init', '--platform', 'all');
assert.equal(r.status, 1);
assert.match(r.stderr, /pincer update/);

// a Codex-only install: no Claude wiring, no Copilot prompts, the .claude tree still ships
const codex = tempDir();
r = pincer(codex, 'init', '--platform', 'codex');
assert.equal(r.status, 0, both(r));
assert.ok(exists(codex, '.agents/skills/pincer-blueprint/SKILL.md'));
assert.ok(exists(codex, '.codex/README.md'));
assert.ok(!exists(codex, 'CLAUDE.md') && !exists(codex, '.claude/settings.json') && !exists(codex, '.github'));
assert.ok(exists(codex, '.claude/skills/pincer-blueprint/SKILL.md'), 'the .claude tree ships everywhere');
assert.deepEqual(JSON.parse(read(codex, '.pincer.json')).platforms, ['codex']);
assert.ok(r.stdout.includes('$pincer-blueprint') && !r.stdout.includes('chat.promptFiles'), r.stdout);
assert.equal(pincer(codex).status, 0);
assert.equal(pincer(codex, 'bogus').status, 1);
assert.equal(pincer(tempDir(), 'init', '--platform', 'vim').status, 1);

console.log('smoke: ok');
